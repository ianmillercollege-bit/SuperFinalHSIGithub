"""Measure the plain-code fact checker against the labelled test set (eval/checker_cases.json).

Run from the repo root or backend/:   python backend/eval/checker_eval.py
It prints the score and writes backend/eval/REPORT.md. tests/test_checker_accuracy.py uses the same
scoring so the numbers cannot quietly get worse.

How it scores each sentence:
- expected issues = the labels that are not CORRECT (a ruleId the checker should raise, incl. NO_FACT);
- found = the ruleIds the checker raised for that sentence.
- An issue is CAUGHT when the checker raises exactly that ruleId.
- A sentence with no expected issue is a FALSE ALARM if the checker raised anything.
"""

import json
import os
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
BACKEND = EVAL_DIR.parent
sys.path.insert(0, str(BACKEND))
os.environ.setdefault("SEED_DIR", str(BACKEND / "seed" / "data"))

RULES = ["PRICE_MISMATCH", "PRICE_OUTDATED", "SPEC_MISMATCH", "INVENTED_FEATURE", "AVAILABILITY_MISMATCH",
         "POLICY_MISMATCH", "UNFAIR_COMPARISON", "SAFETY_LEGAL", "NO_FACT"]


@dataclass
class Score:
    cases: int = 0
    issues: int = 0
    caught: int = 0
    wrong_rule: int = 0                 # an issue was flagged, but under a different rule
    clean: int = 0                      # sentences with no issue to find
    false_alarms: int = 0
    flags: int = 0                      # every ruleId the checker raised
    correct_flags: int = 0
    per_rule: dict = field(default_factory=dict)   # rule -> [caught, total]
    misses: list = field(default_factory=list)     # (case, expected, found)
    alarms: list = field(default_factory=list)     # (case, found)
    hard_caught: int = 0
    hard_total: int = 0

    @property
    def catch_rate(self) -> float:
        return self.caught / self.issues if self.issues else 0.0

    @property
    def false_alarm_rate(self) -> float:
        return self.false_alarms / self.clean if self.clean else 0.0

    @property
    def precision(self) -> float:
        return self.correct_flags / self.flags if self.flags else 0.0


def load_cases() -> list[dict]:
    return json.loads((EVAL_DIR / "checker_cases.json").read_text(encoding="utf-8"))["cases"]


def rules_found(text: str, catalog) -> list[str]:
    from services.checker import check, extract_claims
    return [r.rule_id for r in (check(c, catalog) for c in extract_claims(text, catalog)) if r.rule_id]


def evaluate(cases: list[dict], catalog) -> Score:
    s = Score(per_rule={r: [0, 0] for r in RULES})
    for case in cases:
        s.cases += 1
        expected = Counter(label for label in case["expect"] if label != "CORRECT")
        found = Counter(rules_found(case["text"], catalog))
        hard = "hard" in case.get("note", "")
        s.flags += sum(found.values())
        s.correct_flags += sum((found & expected).values())
        if not expected:
            s.clean += 1
            if found:
                s.false_alarms += 1
                s.alarms.append((case, sorted(found.elements())))
            continue
        for rule, count in expected.items():
            hit = min(count, found[rule])
            s.issues += count
            s.caught += hit
            s.per_rule[rule][0] += hit
            s.per_rule[rule][1] += count
            if hard:
                s.hard_total += count
                s.hard_caught += hit
        if expected - found:
            s.misses.append((case, sorted(expected.elements()), sorted(found.elements())))
            if found:
                s.wrong_rule += 1
    return s


def report(s: Score) -> str:
    lines = [
        "# Fact checker accuracy",
        "",
        "Generated by `backend/eval/checker_eval.py` from the labelled test set `backend/eval/checker_cases.json`",
        f"({s.cases} realistic AI-assistant sentences about the fictional seed catalog, labelled from the verified",
        "product facts). Plain-code checker only (mock mode, no AI).",
        "",
        "| Measure | Result |",
        "|---|---|",
        f"| Mistakes caught, right rule | **{s.caught} of {s.issues} ({s.catch_rate:.0%})** |",
        f"| False alarms on correct sentences | **{s.false_alarms} of {s.clean} ({s.false_alarm_rate:.0%})** |",
        f"| Flags that were right (precision) | {s.correct_flags} of {s.flags} ({s.precision:.0%}) |",
        f"| Of which deliberately hard wording | {s.hard_caught} of {s.hard_total} caught |",
        "",
        "## By rule",
        "",
        "| Rule | Caught |",
        "|---|---|",
    ]
    lines += [f"| `{rule}` | {c} of {t} |" for rule, (c, t) in s.per_rule.items() if t]
    lines += ["", "## Misses (what to improve next)", ""]
    if not s.misses:
        lines.append("None.")
    for case, expected, found in s.misses:
        note = f" _{case['note']}_" if case.get("note") else ""
        lines.append(f"- `{case['id']}` \"{case['text']}\" expected {', '.join(expected)}; "
                     f"found {', '.join(found) or 'nothing'}.{note}")
    lines += ["", "## False alarms", ""]
    if not s.alarms:
        lines.append("None.")
    for case, found in s.alarms:
        lines.append(f"- `{case['id']}` \"{case['text']}\" flagged {', '.join(found)}.")
    return "\n".join(lines) + "\n"


def main() -> None:
    from db import SessionLocal
    from seed_loader import rebuild_database
    from services.checker import Catalog

    rebuild_database()
    with SessionLocal() as db:
        score = evaluate(load_cases(), Catalog(db))
    text = report(score)
    (EVAL_DIR / "REPORT.md").write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    main()
